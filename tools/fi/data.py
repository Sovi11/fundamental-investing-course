"""Load the course's running-example data and fetch real Indian company statements.

Two kinds of data live here:

1. **Course data (offline).** The fictional running examples, Kaveri Pumps & Motors Ltd and
   Nirmal Finance Ltd, are generated by ``tools/running_example/generate.py`` into
   ``tools/data/*.csv``. ``load_kaveri`` and ``load_nirmal`` read those CSVs into DataFrames whose
   **index is the line item** and whose **columns are periods** (``FY21`` ... ``FY26``). Amounts are
   in ₹ crore. Line-item keys are the generator's keys (``rev``, ``mat``, ``ebitda``, ``receivables``,
   ``cfo`` ...); see ``KAVERI_LINE_ITEMS`` for a plain-English description of each one.

2. **Real company data (network).** ``fetch_statements`` pulls income statement, balance sheet
   and cash-flow statement for an NSE/BSE ticker (``"ASIANPAINT.NS"``, ``"500820.BO"``) through
   OpenBB 4.x (``obb.equity.fundamental.income/balance/cash`` with ``provider="yfinance"``) when
   OpenBB is installed, falling back to raw ``yfinance``. ``fetch_price_info`` returns price, market
   cap, share count, beta and the analyst-target fields from ``yf.Ticker(t).info``.

Network caveats (read these before blaming the code):

* **VPNs frequently block Yahoo Finance** (requests to ``fc.yahoo.com`` / ``query2.finance.yahoo.com``
  fail or return empty frames). Disable the VPN before running any yfinance/OpenBB script.
* Yahoo gives at most ~4-5 annual and ~5 quarterly periods. For Indian companies quarterly
  coverage is patchy: quarters can be missing, and the quarterly balance sheet and cash-flow
  statement are often absent for some or all quarters (e.g. in Sep-2026 Asian Paints had no
  quarterly cash flow and only March/September balance sheets on Yahoo). The mandatory balance
  sheet for Indian listed companies is the half-yearly statement of assets and liabilities
  (SEBI LODR Reg. 33 - verify the current text at sebi.gov.in); some companies publish more.
* Vendor data are standardised by Yahoo, not by the company: always tie key lines back to the annual
  report (Module 10.2).
* Amounts from Yahoo are in **rupees**, not crore. Pass ``in_crore=True`` to divide by 1e7.
* Scripts that print ``₹`` on Windows must wrap stdout first::

      import io, sys
      sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
"""
