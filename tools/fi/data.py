_NO_SCALE_PATTERNS = ("eps", "per_share", "shares", "share_issued", "rate", "ratio")


def standardise_statement(df: pd.DataFrame, statement: str, in_crore: bool = False) -> pd.DataFrame:
    """Normalise a raw statement to the course layout and add canonical rows.

    Layout: index = snake_case line item, columns = period-end dates ``"YYYY-MM-DD"`` sorted
    oldest -> newest (same orientation as ``load_kaveri``). Canonical rows (``revenue``,
    ``net_income``, ``cfo``, ``capex`` ...; see ``CANONICAL_ROWS``) are added when missing, taking
    the first available candidate per period - this is where the ``total_revenue`` vs
    ``operating_revenue`` difference is handled.

    ``in_crore=True`` divides monetary rows by 1e7 (per-share, share-count and rate rows untouched).
    """
    if df is None or df.empty:
        return pd.DataFrame()
    out = df.copy()
    out.index = [to_snake_case(i) for i in out.index]
    out = out[~out.index.duplicated(keep="first")]
    cols = []
    for c in out.columns:
        try:
            cols.append(pd.Timestamp(c).strftime("%Y-%m-%d"))
        except (ValueError, TypeError):
            cols.append(str(c))
    out.columns = cols
    out = out.apply(pd.to_numeric, errors="coerce")
    out = out.reindex(sorted(out.columns), axis=1)
    for canon, candidates in CANONICAL_ROWS.get(statement, {}).items():
        if canon in out.index:
            continue
        present = [c for c in candidates if c in out.index]
        if not present:
            continue
        row = out.loc[present[0]].copy()
        for c in present[1:]:
            row = row.fillna(out.loc[c])
        out.loc[canon] = row
    if in_crore:
        scale = [not any(p in idx for p in _NO_SCALE_PATTERNS) for idx in out.index]
        out.loc[scale] = out.loc[scale] / 1e7
    out.index.name = "line_item"
    out.columns.name = "period"
    return out


def revenue_row(income: pd.DataFrame) -> pd.Series:
    """Return revenue from a statement frame, whichever of ``total_revenue``/``operating_revenue`` exists."""
    for key in ("revenue", "total_revenue", "operating_revenue"):
        if key in income.index:
            return income.loc[key]
    raise KeyError("no revenue row (looked for revenue / total_revenue / operating_revenue)")


def _fetch_openbb(statement: str, ticker: str, period: str, provider: str, limit: int | None) -> pd.DataFrame:
    from openbb import obb  # imported lazily: slow, and optional

    fn = {
        "income": obb.equity.fundamental.income,
        "balance": obb.equity.fundamental.balance,
        "cash": obb.equity.fundamental.cash,
    }[statement]
    kwargs: dict[str, Any] = {"symbol": ticker, "provider": provider, "period": period}
    if limit is not None:
        kwargs["limit"] = limit
    res = fn(**kwargs)
    rows = [r.model_dump() if hasattr(r, "model_dump") else dict(r) for r in (res.results or [])]
    if not rows:
        return pd.DataFrame()
    wide = pd.DataFrame(rows)
    if "period_ending" not in wide.columns:
        raise ValueError("OpenBB result has no 'period_ending' column")
    wide = wide.set_index("period_ending").drop(columns=["fiscal_period", "fiscal_year"], errors="ignore")
    return wide.T


def _fetch_yfinance(statement: str, ticker: str, period: str, limit: int | None) -> pd.DataFrame:
    import yfinance as yf

    t = yf.Ticker(ticker)
    getter = {"income": t.get_income_stmt, "balance": t.get_balance_sheet, "cash": t.get_cash_flow}[statement]
    raw = getter(as_dict=False, pretty=False, freq="yearly" if period == "annual" else "quarterly")
    if raw is None or raw.empty:
        return pd.DataFrame()
    if limit is not None:
        raw = raw.iloc[:, :limit]  # Yahoo returns newest first
    return raw


def fetch_statements(
    ticker: str,
    period: str = "annual",
    provider: str = "yfinance",
    *,
    limit: int | None = 5,
    use_openbb: bool | None = None,
    in_crore: bool = False,
) -> dict[str, pd.DataFrame]:
    """Fetch income statement, balance sheet and cash-flow statement for a listed company.

    Parameters
    ----------
    ticker : str
        Yahoo symbol, e.g. ``"ASIANPAINT.NS"`` (NSE) or ``"500820.BO"`` (BSE).
    period : {"annual", "quarter"}
        ``"quarterly"`` is accepted and mapped to ``"quarter"`` (the value OpenBB expects).
    provider : str
        OpenBB provider (default ``"yfinance"``, which needs no API key). The FMP free tier does
        **not** cover Indian listings.
    limit : int or None
        Number of periods (the OpenBB yfinance provider caps this at 5).
    use_openbb : bool or None
        ``None`` (default) uses OpenBB if importable, else yfinance; ``True`` forces OpenBB (errors
        propagate as warnings and the yfinance fallback is still tried); ``False`` skips OpenBB.
    in_crore : bool
        Divide monetary rows by 1e7 (Yahoo reports rupees).

    Returns
    -------
    dict with keys ``"income"``, ``"balance"``, ``"cash"``; each a DataFrame (line item x period-end
    date, oldest -> newest) with canonical rows added (``revenue``, ``net_income``, ``cfo``...).
    A statement that cannot be fetched comes back as an empty DataFrame with a warning.

    Notes
    -----
    Needs network access. **Disable any VPN** - Yahoo Finance endpoints are commonly blocked.
    OpenBB route: ``obb.equity.fundamental.income(symbol=..., provider="yfinance", period="annual")``.
    """
    period = _normalise_period(period)
    if use_openbb is None:
        use_openbb = importlib.util.find_spec("openbb") is not None
    out: dict[str, pd.DataFrame] = {}
    for statement in ("income", "balance", "cash"):
        raw = pd.DataFrame()
        source = None
        if use_openbb:
            try:
                raw = _fetch_openbb(statement, ticker, period, provider, limit)
                source = "openbb"
            except Exception as exc:  # noqa: BLE001 - network/provider errors vary widely
                warnings.warn(f"OpenBB {statement} fetch failed for {ticker} ({exc!r}); trying yfinance",
                              stacklevel=2)
        if raw is None or raw.empty:
            try:
                raw = _fetch_yfinance(statement, ticker, period, limit)
                source = "yfinance"
            except Exception as exc:  # noqa: BLE001
                warnings.warn(f"yfinance {statement} fetch failed for {ticker} ({exc!r}). "
                              "Is a VPN blocking Yahoo Finance?", stacklevel=2)
                raw = pd.DataFrame()
        std = standardise_statement(raw, statement, in_crore=in_crore)
        if std.empty:
            warnings.warn(f"{statement} statement for {ticker} ({period}) is empty", stacklevel=2)
        std.attrs.update(ticker=ticker, period=period, source=source,
                         units="₹ crore" if in_crore else "reporting currency (₹ for Indian listings)")
        out[statement] = std
    return out


