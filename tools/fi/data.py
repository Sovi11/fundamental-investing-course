def to_snake_case(name: str) -> str:
    """Convert Yahoo's CamelCase line items (``"TotalRevenue"``) to OpenBB-style snake_case.

    Mirrors ``openbb_core.provider.utils.helpers.to_snake_case`` so that the OpenBB and raw
    yfinance routes produce the same row names (``"total_revenue"``, ``"basic_eps"``).
    """
    s1 = re.sub("(.)([A-Z][a-z]+)", r"\1_\2", str(name))
    return re.sub("([a-z0-9])([A-Z])", r"\1_\2", s1).lower().replace(" ", "_").replace("__", "_")


def _normalise_period(period: str) -> str:
    p = period.lower().strip()
    if p in {"annual", "a", "year", "yearly", "fy"}:
        return "annual"
    if p in {"quarter", "quarterly", "q"}:  # OpenBB wants "quarter", not "quarterly"
        return "quarter"
    raise ValueError(f"period must be 'annual' or 'quarter', got {period!r}")


