def _load_running_example(name: str) -> ModuleType:
    """Import ``tools/running_example/<name>.py`` as a module (cached).

    The generator scripts re-wrap ``sys.stdout`` at import time (so they can print ₹ on Windows).
    Doing that inside a library call would detach/close the caller's stdout (pytest capture,
    Jupyter), so the import runs with a throw-away stdout that is restored afterwards.
    ``main()`` is never called, so no files are rewritten.
    """
    if name in _MODULE_CACHE:
        return _MODULE_CACHE[name]
    path = RUNNING_EXAMPLE_DIR / f"{name}.py"
    if not path.exists():
        raise FileNotFoundError(f"running-example module not found: {path}")
    spec = importlib.util.spec_from_file_location(f"_fi_running_example_{name}", path)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise ImportError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    saved_stdout = sys.stdout
    sys.stdout = io.TextIOWrapper(io.BytesIO(), encoding="utf-8")
    try:
        spec.loader.exec_module(module)
    finally:
        sys.stdout = saved_stdout
    _MODULE_CACHE[name] = module
    return module


def _read_frame(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path, index_col="line_item")
    df.index.name = "line_item"
    df.columns.name = "period"
    return df.apply(pd.to_numeric, errors="coerce").astype(float)


def kaveri_opening_balance() -> pd.Series:
    """Kaveri's opening balance sheet at 31-Mar-2020 ("FY20"), ₹ crore.

    Needed because FY21 ratios on *average* balances (ROE, ROCE, ROIC) use the FY20 closing
    balance sheet, which is not a column of the annual CSV. Values come straight from the
    generator's ``OPEN`` dict, plus derived ``net_block``, ``equity`` and ``total_assets``.
    """
    gen = _load_running_example("generate")
    o = dict(gen.OPEN)
    o["net_block"] = round(o["gross_block"] - o["acc_dep"], 1)
    o["equity"] = round(o["share_capital"] + o["other_equity"], 1)
    o["total_assets"] = round(
        o["net_block"] + o["cwip"] + o["rou"] + o["intangibles"] + o["inventory"] + o["receivables"]
        + o["oca"] + o["cash"] + o["cur_inv"], 1)
    o["total_le"] = round(
        o["equity"] + o["lt_debt"] + o["st_debt"] + o["lease_liab"] + o["payables"] + o["ocl"] + o["dtl"], 1)
    return pd.Series(o, name="FY20", dtype=float)


def kaveri_market_data() -> pd.DataFrame:
    """Kaveri per-year market data (fictional): share price at 31-March, DPS paid, share counts.

    Rows: ``price`` (₹), ``dps_paid`` (₹, dividend per share paid during the year),
    ``shares`` (crore, basic), ``diluted_shares`` (crore). Columns FY21..FY26.
    """
    gen = _load_running_example("generate")
    k = gen.K
    years = list(gen.YEARS)
    return pd.DataFrame(
        {
            "price": [float(p) for p in k["price_mar"]],
            "dps_paid": [float(d) for d in k["dps_paid"]],
            "shares": [float(k["shares"])] * len(years),
            "diluted_shares": [float(s) for s in k["diluted_shares"]],
        },
        index=years,
    ).T


def load_kaveri(kind: str = "annual") -> pd.DataFrame:
    """Load Kaveri Pumps & Motors Ltd (fictional) data as a line-item x period DataFrame.

    Parameters
    ----------
    kind : {"annual", "ratios", "quarterly"}
        ``"annual"`` - the full P&L, balance sheet and cash-flow statement, FY21-FY26 (₹ crore);
        ``"ratios"`` - the generator's ratio table (decimals, e.g. 0.138 = 13.8%);
        ``"quarterly"`` - Q1 FY26 ... Q1 FY27.

    The annual frame carries metadata in ``df.attrs`` so that ``fi.ratios.ratio_dashboard`` can
    reproduce the course ratio table without extra arguments:

    * ``opening`` (dict) and ``opening_for`` (``"FY21"``): the 31-Mar-2020 balance sheet;
    * ``price``, ``dps_paid``, ``diluted_shares`` (dict by FY), ``shares`` (6.0 crore),
      ``tax_rate`` (0.2517), ``cmp`` (₹390 on 18-Sep-2026), ``units`` ("₹ crore").

    Example
    -------
    >>> df = load_kaveri()
    >>> float(df.at["rev", "FY26"])
    1318.0
    """
    kind = kind.lower()
    if kind not in _KAVERI_FILES:
        raise ValueError(f"kind must be one of {sorted(_KAVERI_FILES)}, got {kind!r}")
    df = _read_frame(DATA_DIR / _KAVERI_FILES[kind])
    gen = _load_running_example("generate")
    df.attrs["company"] = "Kaveri Pumps & Motors Ltd (fictional)"
    df.attrs["units"] = "₹ crore"
    df.attrs["kind"] = kind
    if kind == "annual":
        mkt = kaveri_market_data()
        df.attrs["opening"] = kaveri_opening_balance().to_dict()
        df.attrs["opening_for"] = gen.YEARS[0]
        df.attrs["price"] = mkt.loc["price"].to_dict()
        df.attrs["dps_paid"] = mkt.loc["dps_paid"].to_dict()
        df.attrs["diluted_shares"] = mkt.loc["diluted_shares"].to_dict()
        df.attrs["shares"] = float(gen.K["shares"])
        df.attrs["face_value"] = 5.0
        df.attrs["tax_rate"] = float(gen.K["tax_rate"])
        df.attrs["cmp"] = float(gen.K["cmp"])
    return df


